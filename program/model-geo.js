function isNum(value) {
  return typeof value === "number" && Number.isFinite(value);
}

function isLatLon(point) {
  return !!point
    && isNum(point.lat) && isNum(point.lon)
    && point.lat >= -90 && point.lat <= 90
    && point.lon >= -180 && point.lon <= 180;
}

function usableRing(coverage) {
  if (!Array.isArray(coverage) || coverage.length < 3) return null;
  const ring = coverage.slice();
  const first = ring[0];
  const last = ring[ring.length - 1];
  if (first && last && first.lat === last.lat && first.lon === last.lon) ring.pop();
  if (ring.length < 3) return null;
  for (let i = 0; i < ring.length; i++) {
    if (!isLatLon(ring[i])) return null;
  }
  return ring;
}

export function isCalibrated(entry) {
  if (!entry) return false;
  const world = entry.anchorWorld;
  if (!world || !isNum(world.x) || !isNum(world.z)) return false;
  if (!isLatLon(entry.anchorGeo)) return false;
  if (!isNum(entry.metersPerUnit) || entry.metersPerUnit <= 0) return false;
  if (!isNum(entry.northDegrees)) return false;
  return usableRing(entry.coverage) !== null;
}

function wrap360(degrees) {
  return ((degrees % 360) + 360) % 360;
}

// Ready only when the entry is complete AND its northDegrees is the same
// number the compass uses. The marker then rotates once, inside
// wgs84ToWorld, and nowhere else.
export function markerReady(entry, verifiedNorth) {
  if (!isCalibrated(entry) || !isNum(verifiedNorth)) return false;
  return Math.abs(wrap360(entry.northDegrees) - wrap360(verifiedNorth)) < 1e-6;
}

// Local equirectangular conversion for these small neighborhoods.
// northDegrees is clockwise from world -Z toward +X, the same meaning as
// VERIFIED_NORTH. Applied once here. Not applied to the compass, and the
// compass value is not applied again to the result.
// North-up (0): east increases world +X, north decreases world Z.
// Same conversion as wgs84ToWorld, without requiring a coverage ring.
// The calibration panel uses this to check a landmark before the
// boundary exists. It does not invent an anchor, a scale, or a north.
export function projectToWorld(entry, lat, lon) {
  const world = entry && entry.anchorWorld;
  if (!world || !isNum(world.x) || !isNum(world.z)) return null;
  if (!isLatLon(entry.anchorGeo)) return null;
  if (!isNum(entry.metersPerUnit) || entry.metersPerUnit <= 0) return null;
  if (!isNum(entry.northDegrees)) return null;
  if (!isNum(lat) || !isNum(lon)) return null;
  const lat0 = (entry.anchorGeo.lat * Math.PI) / 180;
  const east = (lon - entry.anchorGeo.lon) * 111320 * Math.cos(lat0);
  const north = (lat - entry.anchorGeo.lat) * 110540;
  const theta = (entry.northDegrees * Math.PI) / 180;
  const cos = Math.cos(theta);
  const sin = Math.sin(theta);
  const rotatedEast = east * cos + north * sin;
  const rotatedNorth = -east * sin + north * cos;
  return {
    x: world.x + rotatedEast / entry.metersPerUnit,
    z: world.z - rotatedNorth / entry.metersPerUnit,
  };
}

export function wgs84ToWorld(entry, lat, lon) {
  if (!isCalibrated(entry)) return null;
  return projectToWorld(entry, lat, lon);
}

const EARTH_M = 6371000;

function wrapDelta(degrees) {
  let d = degrees;
  while (d > 180) d -= 360;
  while (d < -180) d += 360;
  return d;
}

function wrapLon(lon) {
  let x = lon;
  while (x > 180) x -= 360;
  while (x < -180) x += 360;
  return x;
}

function toRad(degrees) {
  return (degrees * Math.PI) / 180;
}

function toDeg(radians) {
  return (radians * 180) / Math.PI;
}

function sphereMeters(lat1, lon1, lat2, lon2) {
  const p1 = toRad(lat1);
  const p2 = toRad(lat2);
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(wrapDelta(lon2 - lon1));
  const h = Math.sin(dLat / 2) ** 2
    + Math.cos(p1) * Math.cos(p2) * Math.sin(dLon / 2) ** 2;
  return 2 * EARTH_M * Math.asin(Math.min(1, Math.sqrt(h)));
}

// WGS84 inverse. Short coverage edges use the sphere; the reported
// distance uses this ellipsoid length when it converges.
function geodesicMeters(lat1, lon1, lat2, lon2) {
  const a = 6378137;
  const f = 1 / 298.257223563;
  const b = (1 - f) * a;
  const phi1 = toRad(lat1);
  const phi2 = toRad(lat2);
  const L = toRad(wrapDelta(lon2 - lon1));
  const U1 = Math.atan((1 - f) * Math.tan(phi1));
  const U2 = Math.atan((1 - f) * Math.tan(phi2));
  const sinU1 = Math.sin(U1);
  const cosU1 = Math.cos(U1);
  const sinU2 = Math.sin(U2);
  const cosU2 = Math.cos(U2);
  let lambda = L;
  let sinSigma = 0;
  let cosSigma = 0;
  let sigma = 0;
  let sinAlpha = 0;
  let cos2Alpha = 0;
  let cos2SigmaM = 0;
  let iter = 0;
  for (; iter < 100; iter++) {
    const sinLambda = Math.sin(lambda);
    const cosLambda = Math.cos(lambda);
    sinSigma = Math.sqrt(
      (cosU2 * sinLambda) ** 2
      + (cosU1 * sinU2 - sinU1 * cosU2 * cosLambda) ** 2
    );
    if (sinSigma === 0) return 0;
    cosSigma = sinU1 * sinU2 + cosU1 * cosU2 * cosLambda;
    sigma = Math.atan2(sinSigma, cosSigma);
    sinAlpha = (cosU1 * cosU2 * sinLambda) / sinSigma;
    cos2Alpha = 1 - sinAlpha ** 2;
    cos2SigmaM = cos2Alpha === 0 ? 0 : cosSigma - (2 * sinU1 * sinU2) / cos2Alpha;
    const C = (f / 16) * cos2Alpha * (2 + f * (4 - 3 * cos2Alpha));
    const next = L + (1 - C) * f * sinAlpha * (
      sigma + C * sinSigma * (cos2SigmaM + C * cosSigma * (-1 + 2 * cos2SigmaM ** 2))
    );
    if (Math.abs(next - lambda) < 1e-12) {
      lambda = next;
      break;
    }
    lambda = next;
  }
  if (iter >= 100) return sphereMeters(lat1, lon1, lat2, lon2);
  const u2 = cos2Alpha * (a * a - b * b) / (b * b);
  const A = 1 + (u2 / 16384) * (4096 + u2 * (-768 + u2 * (320 - 175 * u2)));
  const B = (u2 / 1024) * (256 + u2 * (-128 + u2 * (74 - 47 * u2)));
  const dSigma = B * sinSigma * (
    cos2SigmaM + (B / 4) * (
      cosSigma * (-1 + 2 * cos2SigmaM ** 2)
      - (B / 6) * cos2SigmaM * (-3 + 4 * sinSigma ** 2) * (-3 + 4 * cos2SigmaM ** 2)
    )
  );
  return b * A * (sigma - dSigma);
}

function initialBearing(lat1, lon1, lat2, lon2) {
  const p1 = toRad(lat1);
  const p2 = toRad(lat2);
  const dLon = toRad(wrapDelta(lon2 - lon1));
  const y = Math.sin(dLon) * Math.cos(p2);
  const x = Math.cos(p1) * Math.sin(p2) - Math.sin(p1) * Math.cos(p2) * Math.cos(dLon);
  return Math.atan2(y, x);
}

function destination(lat, lon, bearing, distanceM) {
  const delta = distanceM / EARTH_M;
  const theta = bearing;
  const p1 = toRad(lat);
  const l1 = toRad(lon);
  const p2 = Math.asin(
    Math.sin(p1) * Math.cos(delta) + Math.cos(p1) * Math.sin(delta) * Math.cos(theta)
  );
  const l2 = l1 + Math.atan2(
    Math.sin(theta) * Math.sin(delta) * Math.cos(p1),
    Math.cos(delta) - Math.sin(p1) * Math.sin(p2)
  );
  return { lat: toDeg(p2), lon: wrapLon(toDeg(l2)) };
}

// Closest point on one short great-circle segment. The query can be far
// away. Only the returned point, which lies on the segment, is safe to
// project with the local neighborhood conversion.
function closestOnGeodesic(lat, lon, latA, lonA, latB, lonB) {
  const span = sphereMeters(latA, lonA, latB, lonB);
  const fromStart = sphereMeters(latA, lonA, lat, lon);
  if (!(span > 0.05)) {
    return { lat: latA, lon: lonA, distanceM: geodesicMeters(lat, lon, latA, lonA) };
  }
  const bearingPoint = initialBearing(latA, lonA, lat, lon);
  const bearingSeg = initialBearing(latA, lonA, latB, lonB);
  const delta13 = fromStart / EARTH_M;
  const cross = Math.asin(Math.max(-1, Math.min(1, Math.sin(delta13) * Math.sin(bearingPoint - bearingSeg))));
  const cosCross = Math.cos(cross);
  let along = 0;
  if (cosCross > 1e-12) {
    const cosAlong = Math.max(-1, Math.min(1, Math.cos(delta13) / cosCross));
    along = Math.acos(cosAlong) * EARTH_M;
    if (Math.cos(bearingPoint - bearingSeg) < 0) along = -along;
  }
  if (along <= 0) return { lat: latA, lon: lonA, distanceM: geodesicMeters(lat, lon, latA, lonA) };
  if (along >= span) return { lat: latB, lon: lonB, distanceM: geodesicMeters(lat, lon, latB, lonB) };
  const hit = destination(latA, lonA, bearingSeg, along);
  return { lat: hit.lat, lon: hit.lon, distanceM: geodesicMeters(lat, lon, hit.lat, hit.lon) };
}

function distanceToRing(entry, lat, lon, ring) {
  const nearest = nearestOnRing(entry, lat, lon, ring);
  return nearest ? nearest.distanceM : Infinity;
}

// Closest point on the coverage ring, including the middle of an edge.
// Distance is geodesic. This is not the model's bounding box.
function nearestOnRing(entry, lat, lon, ring) {
  let best = null;
  let second = null;
  for (let i = 0; i < ring.length; i++) {
    const a = ring[i];
    const b = ring[(i + 1) % ring.length];
    const hit = closestOnGeodesic(lat, lon, a.lat, a.lon, b.lat, b.lon);
    if (!Number.isFinite(hit.distanceM)) continue;
    if (!best || hit.distanceM < best.distanceM) {
      second = best;
      best = hit;
    } else if (!second || hit.distanceM < second.distanceM) {
      second = hit;
    }
  }
  if (!best) return null;
  let ambiguous = false;
  if (second) {
    const apart = sphereMeters(best.lat, best.lon, second.lat, second.lon);
    const slack = Math.max(5, best.distanceM * 0.005);
    ambiguous = apart > 20 && second.distanceM - best.distanceM <= slack;
  }
  return { lat: best.lat, lon: best.lon, distanceM: best.distanceM, ambiguous };
}

export function nearestPerimeter(entry, lat, lon) {
  const ring = entry && usableRing(entry.coverage);
  if (!ring || !entry.anchorGeo || !isLatLon(entry.anchorGeo) || !isNum(lat) || !isNum(lon)) return null;
  return nearestOnRing(entry, lat, lon, ring);
}

export function isInsideCoverage(entry, lat, lon) {
  const ring = entry && usableRing(entry.coverage);
  if (!ring || !isNum(lat) || !isNum(lon)) return false;
  return pointInRing(lat, lon, ring);
}

// Even-odd test on raw WGS84. No buffer and no extra margin.
function pointInRing(lat, lon, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const yi = ring[i].lat;
    const xi = ring[i].lon;
    const yj = ring[j].lat;
    const xj = ring[j].lon;
    const crosses = (yi > lat) !== (yj > lat);
    if (!crosses) continue;
    const xHit = ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (lon < xHit) inside = !inside;
  }
  return inside;
}

// "inside": the whole accuracy circle is inside the polygon.
// "outside": the whole circle is outside it.
// "edge": the circle touches or crosses the boundary.
// "unknown": accuracy is missing, so the point is not called inside or outside.
export function classifyCoverage(entry, lat, lon, accuracyM) {
  const ring = entry && usableRing(entry.coverage);
  if (!ring || !entry.anchorGeo || !isLatLon(entry.anchorGeo) || !isNum(lat) || !isNum(lon)) return "outside";
  const known = isNum(accuracyM) && accuracyM >= 0;
  if (!known) return "unknown";
  const inside = pointInRing(lat, lon, ring);
  const distance = distanceToRing(entry, lat, lon, ring);
  if (distance > accuracyM) return inside ? "inside" : "outside";
  return "edge";
}
